/* Win16 GetTempFileName accepted a drive byte (optionally ORed with
 * TF_FORCEDRIVE). The Win32 API replaced that argument with a directory path.
 * Keep the source-level Win16 contract and translate it here so the original
 * file-management code can remain intact.
 */
#ifndef TF_FORCEDRIVE
#define TF_FORCEDRIVE 0x80
#endif
static __inline UINT OpusGetTempFileName(BYTE drive_and_flags,
                                         LPCSTR prefix,
                                         UINT unique,
                                         LPSTR output) {
    CHAR directory[MAX_PATH];
    const BYTE drive = (BYTE)(drive_and_flags & (BYTE)~TF_FORCEDRIVE);

    if ((drive_and_flags & TF_FORCEDRIVE) != 0 && drive != 0) {
        directory[0] = (CHAR)drive;
        directory[1] = ':';
        directory[2] = '\\';
        directory[3] = '\0';
    } else {
        const DWORD length = GetTempPathA((DWORD)sizeof(directory), directory);
        if (length == 0 || length >= sizeof(directory)) {
            return 0;
        }
    }

    return GetTempFileNameA(directory, prefix, unique, output);
}
#ifdef GetTempFileName
#undef GetTempFileName
#endif
#define GetTempFileName(drive, prefix, unique, output) \
    OpusGetTempFileName((BYTE)(drive), (LPCSTR)(prefix), (UINT)(unique), \
                        (LPSTR)(output))

