/* A null Win16 module handle made GetProcAddress fail. On current Windows,
 * passing that invalid handle can instead search the process image. Opus probes
 * retired modules such as KERNEL, GDI, and USER by ordinal, so an unsuccessful
 * probe must not be allowed to resolve an unrelated WORD1 export with the same
 * ordinal.
 */
static __inline FARPROC OpusGetProcAddress(HMODULE module, LPCSTR name) {
    return module != NULL ? GetProcAddress(module, name) : NULL;
}
#define GetProcAddress OpusGetProcAddress

