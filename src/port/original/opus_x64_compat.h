/* Flat-memory equivalents of the CS copy/fill intrinsics. Argument order is
 * intentionally source-first/destination-second to match Opus.
 */
static __inline unsigned char* OpusMoveBytesEnd(const void* source,
                                                void* destination,
                                                size_t count) {
    memmove(destination, source, count);
    return (unsigned char*)destination + count;
}
#define bltbyteNat(source, destination, count) \
    OpusMoveBytesEnd((source), (destination), (size_t)(count))
#define bltbxNat(source, destination, count) \
    OpusMoveBytesEnd((source), (destination), (size_t)(count))
#define bltbcxNat(value, destination, count) \
    memset((destination), (unsigned char)(value), (size_t)(count))
#define BLTBH(source, destination, count) \
    OpusMoveBytesEnd((source), (destination), (size_t)(count))
#define LpOfHp(pointer) ((void*)(pointer))

static __inline void* OpusFillWords(int value, int* destination, size_t count) {
    size_t index;
    for (index = 0; index < count; ++index) {
        destination[index] = value;
    }
    return destination;
}
#define bltcxNat(value, destination, count) \
    OpusFillWords((value), (int*)(destination), (size_t)(count))

